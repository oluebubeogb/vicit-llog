#!/usr/bin/env python3
"""
Builds src/common/utils/qr-font.ts — anti-aliased glyph bitmaps (ASCII 32–126) used to
draw the caption under gate QR codes in pure JS (no system fonts / native canvas needed,
so it renders identically in the node:alpine Docker image).

Font: Inter (SIL Open Font License 1.1). Re-run after changing sizes:
    python3 scripts/build-qr-font.py /path/to/Inter-VariableFont_opsz,wght.ttf
"""
import base64, json, sys, zlib
from PIL import Image, ImageDraw, ImageFont

SRC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/sand-box/google/Inter/Inter-VariableFont_opsz,wght.ttf'
FACES = {'title': (30, 700), 'sub': (19, 500)}

def face(px, wght):
    f = ImageFont.truetype(SRC, px)
    try:
        axes = f.get_variation_axes()
        vals = []
        for a in axes:
            n = a.get('name', b'')
            n = n.decode() if isinstance(n, bytes) else str(n)
            if 'eight' in n.lower(): vals.append(wght)
            elif 'ptical' in n.lower(): vals.append(max(a['minimum'], min(a['maximum'], px)))
            else: vals.append(a['default'])
        f.set_variation_by_axes(vals)
    except Exception as e:
        print('no variation axes:', e, file=sys.stderr)
    return f

out = {}
for key, (px, wght) in FACES.items():
    f = face(px, wght)
    ascent, descent = f.getmetrics()
    glyphs = {}
    for code in range(32, 127):
        ch = chr(code)
        adv = f.getlength(ch)
        l, t, r, b = f.getbbox(ch, anchor='ls')
        w, h = max(0, r - l), max(0, b - t)
        data = b''
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
            data = im.tobytes()
        glyphs[code] = [round(adv, 2), l, t, w, h, base64.b64encode(data).decode()]
    out[key] = {'size': px, 'ascent': ascent, 'descent': descent, 'glyphs': glyphs}

blob = base64.b64encode(zlib.compress(json.dumps(out, separators=(',', ':')).encode(), 9)).decode()
lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
ts = ('/* eslint-disable */\n// GENERATED by scripts/build-qr-font.py — do not edit by hand.\n'
      '// Glyph bitmaps rendered from Inter (SIL Open Font License 1.1, https://rsms.me/inter).\n'
      'export const QR_FONT_DEFLATED_B64 =\n' + ' +\n'.join("  '" + l + "'" for l in lines) + ';\n')
open(sys.argv[2] if len(sys.argv) > 2 else 'src/common/utils/qr-font.ts', 'w').write(ts)
print('bytes', len(blob))
